#!/usr/bin/env bash
# SessionStart: переписать дамп ccfzf в фоне, мимо пикера.
#
# Дамп на машине агрегатора переписывает только опрос пикера (`ccfzf --state`
# освежает его, когда тот старше STATE_DUMP_MAX_AGE), а у скрытого пикера такт
# опроса уходит до восьми минут. Пока дамп стар, трекер окон не может привязать
# окно новой сессии: её в индексе просто нет. Значит и сказать пикеру «состав
# окон изменился» ему нечем, и круг замыкается сам на себе. Разрывает его
# только тот, кто обновит дамп мимо пикера, — этот хук.
#
# Закрывает он ровно один случай: сессию завели мимо пикера, руками в
# терминале. Заведённым из пикера свежесть даёт всплеск опроса после открытия.
#
# Цена: `ccfzf --dump` — около 0,4 с wall и 0,25 с CPU, один раз на рождение
# сессии. Сессия попадает в дамп сразу с именем и каталогом, ещё до того, как
# заведётся транскрипт: ccfzf берёт её из реестра ~/.claude/sessions/<pid>.json.
#
# Хук не ждёт дампа: процесс уходит в фон отвязанным от всех трёх потоков.
# Держи он stdout, Claude Code ждал бы закрытия пайпа, а всё, что SessionStart
# напечатает, попадает в контекст модели.
#
# Какой ccfzf звать:
#   1. CCFZF_BIN, если задан;
#   2. ccfzf того клона, где лежит этот файл, — хук ставится симлинком
#      (hooks/install.sh), и путь разрешается по нему. PATH хука может не
#      содержать каталога, в который положен ccfzf;
#   3. ccfzf с PATH.
# Не нашёлся ни один — хук молча выходит: дамп освежит следующий опрос пикера.
#
# Регистрируется на SessionStart:
#   bash ~/.claude/hooks/ccfzf-dump.sh

set -u

# stdin хука не нужен, но дочитать его надо: писатель не должен получить SIGPIPE.
cat >/dev/null 2>&1 || true

bin="${CCFZF_BIN:-}"
if [ -z "$bin" ]; then
  self="$(readlink -f "${BASH_SOURCE[0]}" 2>/dev/null || true)"
  if [ -n "$self" ]; then
    clone="$(dirname "$(dirname "$self")")"
    [ -x "$clone/ccfzf" ] && bin="$clone/ccfzf"
  fi
fi
[ -n "$bin" ] || bin="$(command -v ccfzf 2>/dev/null || true)"
[ -n "$bin" ] && [ -x "$bin" ] || exit 0

if command -v setsid >/dev/null 2>&1; then
  setsid "$bin" --dump </dev/null >/dev/null 2>&1 &
else
  nohup "$bin" --dump </dev/null >/dev/null 2>&1 &
fi

exit 0
